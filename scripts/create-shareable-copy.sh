#!/usr/bin/env bash
# Create a copy of SheetsCRM safe to zip for private team handoff.
# Includes shared Google OAuth client id/secret from your local .env when present.
# Still excludes Mixmax/SA secrets, overlay DB, node_modules, and .git.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-${ROOT}/../SheetsCRM-share}"

if [[ -e "$DEST" ]]; then
  echo "Destination already exists: $DEST"
  echo "Remove it first or pass a different path:"
  echo "  $0 /path/to/SheetsCRM-share"
  exit 1
fi

# Read KEY=value from ROOT/.env (ignores comments / blank lines; strips optional quotes).
env_value() {
  local key="$1"
  local file="$ROOT/.env"
  local line value

  if [[ ! -f "$file" ]]; then
    echo ""
    return
  fi

  line="$(
    grep -E "^[[:space:]]*${key}=" "$file" | tail -n 1 || true
  )"
  if [[ -z "$line" ]]; then
    echo ""
    return
  fi

  value="${line#*=}"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  if [[ "$value" == \"*\" && "$value" == *\" ]]; then
    value="${value:1:${#value}-2}"
  elif [[ "$value" == \'*\' && "$value" == *\' ]]; then
    value="${value:1:${#value}-2}"
  fi
  printf '%s' "$value"
}

GOOGLE_CLIENT_ID_VALUE="$(env_value GOOGLE_CLIENT_ID)"
GOOGLE_CLIENT_SECRET_VALUE="$(env_value GOOGLE_CLIENT_SECRET)"
DEFAULT_SHEET_URL_VALUE="$(env_value DEFAULT_SHEET_URL)"
SALESFORCE_SEARCH_BASE_URL_VALUE="$(env_value SALESFORCE_SEARCH_BASE_URL)"

OAUTH_INCLUDED=0
USE_MOCK_DATA_VALUE="true"
if [[ -n "$GOOGLE_CLIENT_ID_VALUE" && -n "$GOOGLE_CLIENT_SECRET_VALUE" \
  && "$GOOGLE_CLIENT_ID_VALUE" != *your-google-oauth* \
  && "$GOOGLE_CLIENT_SECRET_VALUE" != *your-google-oauth* ]]; then
  OAUTH_INCLUDED=1
  USE_MOCK_DATA_VALUE="false"
else
  GOOGLE_CLIENT_ID_VALUE="${GOOGLE_CLIENT_ID_VALUE:-your-google-oauth-client-id.apps.googleusercontent.com}"
  GOOGLE_CLIENT_SECRET_VALUE="${GOOGLE_CLIENT_SECRET_VALUE:-your-google-oauth-client-secret}"
fi

if [[ -z "$DEFAULT_SHEET_URL_VALUE" || "$DEFAULT_SHEET_URL_VALUE" == *YOUR_SPREADSHEET_ID* ]]; then
  DEFAULT_SHEET_URL_VALUE="https://docs.google.com/spreadsheets/d/YOUR_SPREADSHEET_ID/edit?gid=YOUR_TAB_GID"
fi

if [[ -z "$SALESFORCE_SEARCH_BASE_URL_VALUE" ]]; then
  SALESFORCE_SEARCH_BASE_URL_VALUE="https://your-org.my.salesforce.com/_ui/search/ui/UnifiedSearchResults"
fi

echo "Creating shareable copy at:"
echo "  $DEST"
echo
if [[ "$OAUTH_INCLUDED" -eq 1 ]]; then
  echo "Including Google OAuth client id/secret from your local .env"
  echo "(for private zip handoff). Mixmax / service-account secrets stay out."
else
  echo "No usable Google OAuth values found in $ROOT/.env"
  echo "Share copy will use placeholders — coworker must paste Client ID/Secret."
fi
echo

mkdir -p "$DEST"

rsync -a \
  --exclude 'node_modules' \
  --exclude '.next' \
  --exclude '.git' \
  --exclude '.env' \
  --exclude '.env.*' \
  --exclude 'data/*.db' \
  --exclude 'data/*.db-*' \
  --exclude 'data/attachment-folder-config.json' \
  --exclude '.DS_Store' \
  --exclude 'coverage' \
  --exclude 'sheets-crm-tmp' \
  "$ROOT/" "$DEST/"

mkdir -p "$DEST/data"

# Shell-escape values for a double-quoted .env line.
env_escape() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

{
  echo "# SheetsCRM — private team handoff .env"
  echo "# Generated by scripts/create-shareable-copy.sh"
  echo "# Do not commit this file or upload the zip to a public location."
  echo "GOOGLE_CLIENT_ID=\"$(env_escape "$GOOGLE_CLIENT_ID_VALUE")\""
  echo "GOOGLE_CLIENT_SECRET=\"$(env_escape "$GOOGLE_CLIENT_SECRET_VALUE")\""
  echo "NEXT_PUBLIC_APP_URL=http://localhost:3000"
  echo
  echo "NEXT_PUBLIC_AUTO_REFRESH_SECONDS=60"
  echo
  echo "GOOGLE_SERVICE_ACCOUNT_EMAIL="
  echo "GOOGLE_PRIVATE_KEY="
  echo
  echo "DEFAULT_SHEET_URL=\"$(env_escape "$DEFAULT_SHEET_URL_VALUE")\""
  echo
  echo "SALESFORCE_SEARCH_BASE_URL=\"$(env_escape "$SALESFORCE_SEARCH_BASE_URL_VALUE")\""
  echo
  echo "GMAIL_SENDER_EMAIL="
  echo
  echo "OVERLAY_DB_PATH=./data/overlay.db"
  echo
  echo "MIXMAX_API_TOKEN="
  echo
  echo "USE_MOCK_DATA=${USE_MOCK_DATA_VALUE}"
} > "$DEST/.env"

# Example MM directory (no real employee emails)
if [[ -f "$ROOT/data/market-managers.example.json" ]]; then
  cp "$ROOT/data/market-managers.example.json" "$DEST/data/market-managers.json"
else
  cat > "$DEST/data/market-managers.json" <<'EOF'
{
  "updatedAt": "2000-01-01T00:00:00.000Z",
  "managers": [
    { "name": "Example Manager", "email": "manager@example.com" }
  ]
}
EOF
fi

# Scrub hard-coded example sheet IDs from the copy (configure via Setup UI instead)
if [[ "$(uname)" == "Darwin" ]]; then
  SED_INPLACE=(-i '')
else
  SED_INPLACE=(-i)
fi

sed "${SED_INPLACE[@]}" \
  's|1Kj8p-USf20vZREe-Cxg2c28vq4ppTwmgr05lYGxJebg|YOUR_SPREADSHEET_ID|g' \
  "$DEST/src/lib/default-sheet-config.ts" \
  "$DEST/.env.example" 2>/dev/null || true

sed "${SED_INPLACE[@]}" \
  's|223304028|YOUR_TAB_GID|g' \
  "$DEST/src/lib/default-sheet-config.ts" \
  "$DEST/.env.example" 2>/dev/null || true

sed "${SED_INPLACE[@]}" \
  's|https://docs.google.com/spreadsheets/d/1Kj8p-USf20vZREe-Cxg2c28vq4ppTwmgr05lYGxJebg/edit?gid=223304028|https://docs.google.com/spreadsheets/d/YOUR_SPREADSHEET_ID/edit?gid=YOUR_TAB_GID|g' \
  "$DEST/.env.example" 2>/dev/null || true

if [[ "$OAUTH_INCLUDED" -eq 1 ]]; then
  cat > "$DEST/SHARE_PACKAGING.txt" <<'EOF'
SheetsCRM — private team shareable copy
=======================================

This folder was generated for private zip handoff.

Included:
  - Shared Google OAuth Client ID + Client Secret (from the exporter's .env)
  - USE_MOCK_DATA=false so Sign in with Google can use live APIs

Still excluded:
  - Mixmax token, service-account private key
  - Local overlay.db / WAL files
  - node_modules, .next, .git

Your coworker should:
  1. Unzip the folder
  2. Double-click Install SheetsCRM.command (first Mac), then Open SheetsCRM.command
  3. Click Sign in with Google (same org OAuth client; their own Google account)
  4. Connect their intake sheet in Setup → Sheet mapping
  5. Paste their Market Manager list in Setup → Market managers

Later updates: unzip a new share beside the install, then in the existing folder
double-click Update SheetsCRM.command and choose the new unzipped folder.
(First update on an older install: from the NEW unzip run
  bash scripts/update-local-install.sh --apply-to "/path/to/existing/SheetsCRM")

Do not upload this zip to a public link or commit the included .env to git.
EOF
else
  cat > "$DEST/SHARE_PACKAGING.txt" <<'EOF'
SheetsCRM — shareable copy
==========================

This folder was generated without usable Google OAuth credentials
(exporter .env was missing Client ID/Secret).

Before zipping, confirm:
  - No overlay.db was copied
  - .env still has placeholder OAuth values — paste the team Client ID/Secret

Your coworker should:
  1. Unzip the folder
  2. Edit .env (or Setup → Environment) with the shared Google OAuth client ID/secret
  3. Set USE_MOCK_DATA=false
  4. Double-click Install SheetsCRM.command (first Mac), then Open SheetsCRM.command
  5. Sign in with Google, then connect their intake sheet in Setup

Later updates: use Update SheetsCRM.command in the existing install against a new unzip.

Do not commit real .env files or data/overlay.db to git.
EOF
fi

echo "Done."
echo
echo "Excluded: node_modules, .next, .git, Mixmax/SA secrets, overlay.db, WAL/SHM"
if [[ "$OAUTH_INCLUDED" -eq 1 ]]; then
  echo "Included in .env: GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET, USE_MOCK_DATA=false"
else
  echo "OAuth: placeholders only (set values in your local .env, then re-run share:export)"
fi
echo
echo "Next steps:"
echo "  cd $(dirname "$DEST")"
echo "  zip -r SheetsCRM-share.zip $(basename "$DEST")"
echo
echo "See $DEST/SHARE_PACKAGING.txt for a checklist."
